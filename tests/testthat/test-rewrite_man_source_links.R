# Build a package root holding one .Rd file and the rendered HTML of the man
# page Quarto produced from it, with the repo-action links Quarto writes when
# the site sets `repo-actions:`.
local_man_site <- function(
    topic,
    rd_lines,
    r_files = character(0),
    env = parent.frame()
) {
    root <- withr::local_tempdir(.local_envir = env)
    fs::dir_create(fs::path_join(c(root, "man")))
    fs::dir_create(fs::path_join(c(root, "R")))
    fs::dir_create(fs::path_join(c(root, "docs", "man")))

    if (length(rd_lines) > 0) {
        writeLines(
            rd_lines,
            fs::path_join(c(root, "man", paste0(topic, ".Rd")))
        )
    }
    for (f in r_files) {
        writeLines("NULL", fs::path_join(c(root, f)))
    }

    html <- fs::path_join(c(root, "docs", "man", paste0(topic, ".html")))
    writeLines(
        c(
            "<div class=\"toc-actions\"><ul>",
            sprintf(
                "<li><a href=\"https://github.com/user/pkg/edit/main/man/%s.qmd\" class=\"toc-action\">Edit this page</a></li>",
                topic
            ),
            sprintf(
                "<li><a href=\"https://github.com/user/pkg/blob/main/man/%s.qmd\" class=\"toc-action\">View source</a></li>",
                topic
            ),
            "<li><a href=\"https://github.com/user/pkg/issues\" class=\"toc-action\">Report an issue</a></li>",
            "</ul></div>"
        ),
        html
    )

    list(root = root, html = html)
}

roxygen_rd <- function(source_line) {
    c(
        "% Generated by roxygen2: do not edit by hand",
        source_line,
        "\\name{topic}",
        "\\title{Topic}"
    )
}

test_that("a roxygen-generated man page links at the R file it was written in", {
    site <- local_man_site(
        "calculate_summary",
        roxygen_rd("% Please edit documentation in R/calculate_summary.R"),
        r_files = "R/calculate_summary.R"
    )

    .rewrite_man_source_links(
        fs::path_join(c(site$root, "docs")),
        site$root
    )

    out <- paste(.readlines(site$html), collapse = "\n")
    expect_true(grepl(
        'href="https://github.com/user/pkg/blob/main/R/calculate_summary.R"',
        out,
        fixed = TRUE
    ))
    ### the "Edit this page" action names the same input file, so it is
    ### repointed too
    expect_true(grepl(
        'href="https://github.com/user/pkg/edit/main/R/calculate_summary.R"',
        out,
        fixed = TRUE
    ))
    expect_false(grepl(".qmd", out, fixed = TRUE))
    ### "Report an issue" is built from the repository URL alone
    expect_true(grepl(
        'href="https://github.com/user/pkg/issues"',
        out,
        fixed = TRUE
    ))
})

test_that("a hand-written man page links at the .Rd file, which is its source", {
    site <- local_man_site(
        "handwritten",
        c("\\name{handwritten}", "\\title{Handwritten}")
    )

    .rewrite_man_source_links(
        fs::path_join(c(site$root, "docs")),
        site$root
    )

    out <- paste(.readlines(site$html), collapse = "\n")
    expect_true(grepl(
        'href="https://github.com/user/pkg/blob/main/man/handwritten.Rd"',
        out,
        fixed = TRUE
    ))
    expect_false(grepl(".qmd", out, fixed = TRUE))
})

test_that("a topic documented in several R files links at the first of them", {
    ### roxygen2 wraps this comment at 80 characters, so a long list arrives
    ### as a block of `%` lines rather than as one line
    site <- local_man_site(
        "spread",
        c(
            "% Generated by roxygen2: do not edit by hand",
            "% Please edit documentation in R/spread_first.R,",
            "%   R/spread_second.R",
            "\\name{spread}",
            "\\title{Spread}"
        ),
        r_files = c("R/spread_first.R", "R/spread_second.R")
    )

    .rewrite_man_source_links(
        fs::path_join(c(site$root, "docs")),
        site$root
    )

    out <- paste(.readlines(site$html), collapse = "\n")
    expect_true(grepl(
        'href="https://github.com/user/pkg/blob/main/R/spread_first.R"',
        out,
        fixed = TRUE
    ))
})

