test_that("a topic whose name carries regex metacharacters is matched literally", {
    site <- local_man_site(
        "sub-.foo",
        roxygen_rd("% Please edit documentation in R/subset.R"),
        r_files = "R/subset.R"
    )
    ### a second link on the same page, naming a topic that differs only where
    ### an unescaped `.` would match any character
    decoy <- paste0(
        '<a href="https://github.com/user/pkg/blob/main/man/sub-Xfoo.qmd"',
        ' class="toc-action">elsewhere</a>'
    )
    writeLines(c(.readlines(site$html), decoy), site$html)

    .rewrite_man_source_links(
        fs::path_join(c(site$root, "docs")),
        site$root
    )

    out <- paste(.readlines(site$html), collapse = "\n")
    expect_true(grepl(
        'href="https://github.com/user/pkg/blob/main/R/subset.R"',
        out,
        fixed = TRUE
    ))
    expect_true(grepl(
        'href="https://github.com/user/pkg/blob/main/man/sub-Xfoo.qmd"',
        out,
        fixed = TRUE
    ))
})

test_that("a link that is not a repo action is left alone", {
    ### same trailing path, same topic, but no `/blob/` or `/edit/` segment --
    ### so it is an ordinary link in the page body, not a repo action
    site <- local_man_site(
        "plain",
        roxygen_rd("% Please edit documentation in R/plain.R"),
        r_files = "R/plain.R"
    )
    body_link <- '<a href="https://example.org/man/plain.qmd">reference</a>'
    writeLines(c(.readlines(site$html), body_link), site$html)

    .rewrite_man_source_links(
        fs::path_join(c(site$root, "docs")),
        site$root
    )

    out <- paste(.readlines(site$html), collapse = "\n")
    expect_true(grepl(
        'href="https://example.org/man/plain.qmd"',
        out,
        fixed = TRUE
    ))
    ### the repo actions on the same page are still rewritten
    expect_true(grepl(
        'href="https://github.com/user/pkg/blob/main/R/plain.R"',
        out,
        fixed = TRUE
    ))
})

test_that("a body link to the same forge path is left alone", {
