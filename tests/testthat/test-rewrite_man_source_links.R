test_that("the toc-action class is matched as a token, not as a substring", {
    root <- withr::local_tempdir()
    html <- fs::path_join(c(root, "tok.html"))
    writeLines(
        c(
            ### a genuine repo action carrying a second class
            paste0(
                '<a href="https://github.com/user/pkg/blob/main/man/tok.qmd"',
                ' class="toc-action external">src</a>'
            ),
            ### a body link whose attribute merely ends in "class"
            paste0(
                '<a href="https://github.com/user/pkg/blob/main/man/tok.qmd"',
                ' data-class="toc-action">elsewhere</a>'
            ),
            ### and one whose class merely contains the name
            paste0(
                '<a href="https://github.com/user/pkg/blob/main/man/tok.qmd"',
                ' class="not-toc-action">elsewhere</a>'
            )
        ),
        html
    )

    .rewrite_man_source_links_one(html, "tok", "R/tok.R")

    out <- .readlines(html)
    expect_true(grepl("/blob/main/R/tok.R\"", out[1], fixed = TRUE))
    expect_true(grepl("/blob/main/man/tok.qmd\"", out[2], fixed = TRUE))
    expect_true(grepl("/blob/main/man/tok.qmd\"", out[3], fixed = TRUE))
})

test_that("non-ASCII text elsewhere on the page survives the rewrite", {
    ### Quarto writes UTF-8; a re-encode would touch every line, not only the
    ### rewritten one. The characters are built by code point so this file
    ### stays ASCII, per the repo's own convention.
    root <- withr::local_tempdir()
    html <- fs::path_join(c(root, "utf8.html"))
    accented <- paste0(
        "<p>fonction ",
        intToUtf8(c(233L, 99L, 114L, 105L, 116L, 101L)),
        " en fran",
        intToUtf8(c(231L, 97L, 105L, 115L)),
        " ",
        intToUtf8(8212L),
        " r",
        intToUtf8(c(233L, 115L, 117L, 109L, 233L)),
        "</p>"
    )
    writeLines(
        c(
            paste0(
                '<a href="https://github.com/user/pkg/blob/main/man/utf8.qmd"',
                ' class="toc-action">src</a>'
            ),
            accented
        ),
        html,
        useBytes = TRUE
    )

    .rewrite_man_source_links_one(html, "utf8", "R/utf8.R")

    after <- readLines(html, warn = FALSE, encoding = "UTF-8")
    expect_true(grepl("/blob/main/R/utf8.R", after[1], fixed = TRUE))
    ### byte-identical to what was written, whatever the session locale is
    expect_equal(charToRaw(after[2]), charToRaw(accented))
})

test_that("a source path is percent-encoded before it becomes an href", {
    ### `#` would otherwise start a fragment and the forge would receive
    ### `src/model` instead of the file
    root <- withr::local_tempdir()
    html <- fs::path_join(c(root, "enc.html"))
    writeLines(
        paste0(
            '<a href="https://github.com/user/pkg/blob/main/man/enc.qmd"',
            ' class="toc-action">src</a>'
        ),
        html
    )

    .rewrite_man_source_links_one(html, "enc", "src/model#v2.cpp")

    expect_equal(
        .readlines(html),
        paste0(
            '<a href="https://github.com/user/pkg/blob/main/src/model%23v2.cpp"',
            ' class="toc-action">src</a>'
        )
    )
})

test_that("a backslash in the source path cannot become a backreference", {
    ### `@backref` takes any path; encoding it removes the backslash before it
    ### can read as a backreference in the replacement
    root <- withr::local_tempdir()
    html <- fs::path_join(c(root, "backref.html"))
    writeLines(
        paste0(
            '<a href="https://github.com/user/pkg/blob/main/man/backref.qmd"',
            ' class="toc-action">src</a>'
        ),
        html
    )

    .rewrite_man_source_links_one(html, "backref", "src/code\\1.cpp")

    expect_equal(
        .readlines(html),
        paste0(
            '<a href="https://github.com/user/pkg/blob/main/src/code%5C1.cpp"',
            ' class="toc-action">src</a>'
        )
    )
})

test_that("a site with no repo-action links renders nothing to rewrite", {
    site <- local_man_site(
        "plain",
        roxygen_rd("% Please edit documentation in R/plain.R"),
        r_files = "R/plain.R"
    )
    html <- fs::path_join(c(site$root, "docs", "man", "plain.html"))
    writeLines("<p>No repo actions here.</p>", html)
    before <- .readlines(html)

    .rewrite_man_source_links(
        fs::path_join(c(site$root, "docs")),
        site$root
    )

    expect_equal(.readlines(html), before)
})

test_that("a site with no man/ directory is a no-op", {
    root <- withr::local_tempdir()
    fs::dir_create(fs::path_join(c(root, "docs")))
    expect_silent(.rewrite_man_source_links(
        fs::path_join(c(root, "docs")),
        root
    ))
})
